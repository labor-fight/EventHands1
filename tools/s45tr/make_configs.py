#!/usr/bin/env python3
"""Write the S45-TR configs: the frozen S45 config + exactly one registered change each (tools/s45tr/common.py ARMS).

Refuses to overwrite; the configs are frozen by tools/s45tr/freeze.py before any reading.
"""
from __future__ import annotations

from pathlib import Path
import sys

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from tools.s45tr.common import (ARMS, CONFIGS, FORMAL_ARMS, S45_CONFIG, S45_CONFIG_SHA256, config_path,  # noqa: E402
                                expected_raw, require, sha)

HEADER = ("# S45-TR (docs/EXPERIMENT_RECORDS.md#s45tr-prereg-20261030), generated by tools/s45tr/make_configs.py from\n"
          "# configs/c1sf_20261029/r2/c1sf_so3_s3407.yaml (S45); arm {arm}, phase {phase}; registered change: {change}\n")


def main():
    require(sha(S45_CONFIG) == S45_CONFIG_SHA256, "S45 config changed")
    s45 = yaml.safe_load(S45_CONFIG.read_text())
    CONFIGS.mkdir(parents=True, exist_ok=True)
    for arm in ARMS:
        for phase in ("preflight", "formal"):
            if phase == "formal" and arm not in FORMAL_ARMS:
                continue
            target = config_path(arm, phase)
            body = yaml.safe_dump(expected_raw(arm, phase, s45), sort_keys=True, allow_unicode=True)
            with target.open("x") as stream:
                stream.write(HEADER.format(arm=arm, phase=phase, change=ARMS[arm] or "none (S45 code replay)") + body)
            print(target)


if __name__ == "__main__":
    main()
