#!/usr/bin/env python3
"""Write the S45-PX configs: S45's frozen config with `S45PX {ARM, FRAME}` in place of `C1SF` (one change).

Refuses to overwrite; the configs are frozen by tools/s45px/run.py freeze before any reading.
"""
from __future__ import annotations

from pathlib import Path
import sys

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from tools.frozen import accepts  # noqa: E402
from tools.s45px.common import ARMS, CONFIGS, S45_CONFIG, S45_CONFIG_SHA256, config_path, expected_raw, require  # noqa: E402

HEADER = ("# S45-PX (docs/EXPERIMENT_RECORDS.md#s45px-prereg-20261030), generated by tools/s45px/make_configs.py from\n"
          "# configs/c1sf_20261029/r2/c1sf_so3_s3407.yaml (S45); arm {arm}, phase {phase}; added vertex frame: {frame}\n")


def main():
    require(accepts(S45_CONFIG, S45_CONFIG_SHA256), "S45 config changed")
    s45 = yaml.safe_load(S45_CONFIG.read_text())
    CONFIGS.mkdir(parents=True, exist_ok=True)
    for arm in ARMS:
        for phase in ("preflight", "formal"):
            body = yaml.safe_dump(expected_raw(arm, phase, s45), sort_keys=True, allow_unicode=True)
            with config_path(arm, phase).open("x") as stream:
                stream.write(HEADER.format(arm=arm, phase=phase, frame=ARMS[arm]) + body)
            print(config_path(arm, phase))


if __name__ == "__main__":
    main()
