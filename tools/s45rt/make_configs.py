#!/usr/bin/env python3
"""Write the S45-RT T1p configs: S45's frozen config + face_route with the frozen T0P's routes (one change).

Refuses to overwrite; the configs are frozen by tools/s45rt/freeze_plan2.py before any plan-2 reading.
"""
from __future__ import annotations

from pathlib import Path
import sys

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from tools.s45rt.common import S45_CONFIG  # noqa: E402
from tools.s45rt.plan2 import ARMS, CONFIGS, config_path, expected_raw  # noqa: E402

HEADER = ("# S45-RT (docs/EXPERIMENT_RECORDS.md#s45rt-prereg-20261031), generated by tools/s45rt/make_configs.py from\n"
          "# configs/c1sf_20261029/r2/c1sf_so3_s3407.yaml (S45); arm {arm}, phase {phase}; registered change:\n"
          "# MODEL.XAG_ASSOC face_route, MODEL.XAG_GNN legacy, S45RT routes from the frozen T0P\n")


def main():
    s45 = yaml.safe_load(S45_CONFIG.read_text())
    CONFIGS.mkdir(parents=True, exist_ok=True)
    for arm in ARMS:
        for phase in ("preflight", "formal"):
            body = yaml.safe_dump(expected_raw(arm, phase, s45), sort_keys=True, allow_unicode=True)
            with config_path(arm, phase).open("x") as stream:
                stream.write(HEADER.format(arm=arm, phase=phase) + body)
            print(config_path(arm, phase))


if __name__ == "__main__":
    main()
