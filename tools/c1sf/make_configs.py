#!/usr/bin/env python3
"""Write the C1SF configs: canonical C1 + exactly one registered change each (tools/c1sf/common.py ARMS).

Refuses to overwrite; the configs are frozen by tools/c1sf/freeze.py before any reading.
"""
from __future__ import annotations

from pathlib import Path
import sys

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from tools.c1sf.common import ARMS, CANONICAL, CONFIGS, FORMAL_ARMS, config_path, expected_raw  # noqa: E402

HEADER = ("# C1SF (docs/EXPERIMENT_RECORDS.md#c1sf-prereg-20261029), generated by tools/c1sf/make_configs.py from\n"
          "# configs/xyz_c1_repro_20261018/xyz_c1_stable_s3407.yaml; arm {arm}, phase {phase}; registered change: {change}\n")


def main():
    canonical = yaml.safe_load(CANONICAL.read_text())
    CONFIGS.mkdir(parents=True, exist_ok=True)
    for arm in ARMS:
        for phase in ("preflight", "formal"):
            if phase == "formal" and arm not in FORMAL_ARMS:
                continue
            target = config_path(arm, phase)
            body = yaml.safe_dump(expected_raw(arm, phase, canonical), sort_keys=True, allow_unicode=True)
            with target.open("x") as stream:
                stream.write(HEADER.format(arm=arm, phase=phase, change=ARMS[arm] or "none (C1 code replay)") + body)
            print(target)


if __name__ == "__main__":
    main()
