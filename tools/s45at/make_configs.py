#!/usr/bin/env python3
"""Write the S45-AT configs: each arm's base config (S45 or S45-TR T1d) + its one registered change.

Refuses to overwrite; the configs are frozen in outputs/s45at/20261031/protocol.json before any reading.
"""
from __future__ import annotations

from pathlib import Path
import sys

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from tools.s45at.common import ARMS, CONFIGS, base_config, config_path, expected_raw  # noqa: E402

HEADER = ("# S45-AT (docs/EXPERIMENT_RECORDS.md#s45at-prereg-20261031), generated by tools/s45at/make_configs.py from\n"
          "# {base}; arm {arm}, phase {phase}; registered change: {change}\n")


def main():
    CONFIGS.mkdir(parents=True, exist_ok=True)
    for arm, spec in ARMS.items():
        raw = yaml.safe_load(base_config(arm).read_text())
        change = dict(spec["change"], **({"training split without": spec["exclude_subject"]} if "exclude_subject" in spec else {}),
                      **({"sampler": spec["sampler"]} if "sampler" in spec else {}))
        for phase in ("preflight", "formal"):
            body = yaml.safe_dump(expected_raw(arm, phase, raw), sort_keys=True, allow_unicode=True)
            with config_path(arm, phase).open("x") as stream:
                stream.write(HEADER.format(base=base_config(arm).relative_to(Path(__file__).resolve().parents[2]),
                                           arm=arm, phase=phase, change=change) + body)
            print(config_path(arm, phase))


if __name__ == "__main__":
    main()
