#!/usr/bin/env python3
"""Write the S45-CT configs: S45-TR T1d's frozen config with `S45CT {ARM, MODE}` in place of `S45TR` (one change).

Refuses to overwrite; the configs are frozen by tools/s45ct/run.py freeze before any reading.
"""
from __future__ import annotations

from pathlib import Path
import sys

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from tools.s45ct.common import ARMS, CONFIGS, FORMAL_ARMS, T1D_CONFIG, config_path, expected_raw  # noqa: E402

HEADER = ("# S45-CT (docs/EXPERIMENT_RECORDS.md#s45ct-prereg-20261030), generated by tools/s45ct/make_configs.py from\n"
          "# configs/s45tr_20261030/s45tr_t1d_s3407.yaml (S45-TR T1d); arm {arm}, phase {phase}; route corruption: {mode}\n")


def main():
    t1d = yaml.safe_load(T1D_CONFIG.read_text())
    CONFIGS.mkdir(parents=True, exist_ok=True)
    for arm in ARMS:
        for phase in ("preflight", "formal"):
            if phase == "formal" and arm not in FORMAL_ARMS:
                continue
            body = yaml.safe_dump(expected_raw(arm, phase, t1d), sort_keys=True, allow_unicode=True)
            with config_path(arm, phase).open("x") as stream:
                stream.write(HEADER.format(arm=arm, phase=phase, mode=ARMS[arm] or "none (T1d code replay)") + body)
            print(config_path(arm, phase))


if __name__ == "__main__":
    main()
